export function relatedProducts(product: Product, limit = 4): Product[] {
  const explicit = (product.related ?? [])
    .map((s) => productBySlug.get(s))
    .filter((p): p is Product => Boolean(p));

  if (explicit.length >= limit) return explicit.slice(0, limit);

  const sameCategory = products.filter(
    (p) => p.category === product.category && p.slug !== product.slug && !explicit.includes(p),
  );
  return [...explicit, ...sameCategory].slice(0, limit);
}

/** Every distinct vehicle mentioned across the catalogue, for the fitment filter. */
export function allFitments(): string[] {
  const set = new Set<string>();
  for (const p of products) {
    for (const f of p.fitment ?? []) {
      if (f !== "Universal" && !f.includes("confirm") && !f.includes("—")) set.add(f);
    }
  }
  return [...set].sort();
}

export function priceRange(product: Product): { min: number; max: number } {
  if (!product.variants?.length) return { min: product.price, max: product.price };
  const prices = product.variants.map((v) => v.price);
  return { min: Math.min(...prices), max: Math.max(...prices) };
}
